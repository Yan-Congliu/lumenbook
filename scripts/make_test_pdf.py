#!/usr/bin/env python3
"""生成一个多页测试 PDF（纯 ASCII，手工拼 PDF 语法，不依赖第三方库）。

用法：
  python scripts/make_test_pdf.py [-o dist/test-pdf.pdf] [--pages 4]
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.stdout.reconfigure(encoding="utf-8", errors="replace")


def build_pdf(pages: int) -> bytes:
    page_w, page_h = 595, 842  # A4 @72dpi

    objects: list[bytes] = []

    def add(body: bytes) -> int:
        objects.append(body)
        return len(objects)

    # 1: Catalog, 2: Pages, 3: Font
    catalog_id = add(b"<< /Type /Catalog /Pages 2 0 R >>")
    pages_id = add(b"")  # 先占位，后面回填
    font_id = add(b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>")

    page_ids: list[int] = []
    for i in range(pages):
        lines = [
            f"LumenBook PDF test - page {i + 1} / {pages}",
            "",
            "This page is generated by scripts/make_test_pdf.py.",
            "It exists so the PDF reader can be tested without",
            "hunting for a real book first.",
            "",
            "Check: page turning, progress bar, tap zones,",
            "pinch to zoom, and that the page you left",
            "is the page you come back to.",
            "",
            f"page-{i + 1}",
        ]
        text_cmds = [b"BT", b"/F1 18 Tf", b"60 760 Td"]
        for n, line in enumerate(lines):
            size = 22 if n == 0 else 13
            text_cmds.append(b"/F1 %d Tf" % size)
            text_cmds.append(b"(%s) Tj" % line.encode("ascii"))
            text_cmds.append(b"0 -28 Td")
        text_cmds.append(b"ET")

        # 页面右下角画一个方块，用来看缩放是否糊
        rect = b"0.65 0.46 0.30 rg 420 80 100 100 re f"

        content = b"\n".join(text_cmds) + b"\n" + rect + b"\n"
        content_id = add(
            b"<< /Length %d >>\nstream\n" % len(content) + content + b"endstream"
        )
        page_dict = (
            "<< /Type /Page /Parent %d 0 R /MediaBox [0 0 %d %d] "
            "/Resources << /Font << /F1 %d 0 R >> >> /Contents %d 0 R >>"
        ) % (pages_id, page_w, page_h, font_id, content_id)
        page_id = add(page_dict.encode("ascii"))
        page_ids.append(page_id)

    kids = b" ".join(b"%d 0 R" % pid for pid in page_ids)
    objects[pages_id - 1] = b"<< /Type /Pages /Count %d /Kids [%s] >>" % (pages, kids)

    out = bytearray(b"%PDF-1.4\n")
    offsets = [0]
    for n, body in enumerate(objects, start=1):
        offsets.append(len(out))
        out += b"%d 0 obj\n" % n + body + b"\nendobj\n"

    xref_at = len(out)
    out += b"xref\n0 %d\n" % (len(objects) + 1)
    out += b"0000000000 65535 f \n"
    for off in offsets[1:]:
        out += b"%010d 00000 n \n" % off
    out += b"trailer\n<< /Size %d /Root %d 0 R >>\nstartxref\n%d\n%%%%EOF\n" % (
        len(objects) + 1,
        catalog_id,
        xref_at,
    )
    return bytes(out)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("-o", "--out", default="dist/test-pdf.pdf")
    ap.add_argument("--pages", type=int, default=4)
    a = ap.parse_args()

    path = Path(a.out)
    path.parent.mkdir(parents=True, exist_ok=True)
    data = build_pdf(max(1, a.pages))
    path.write_bytes(data)
    print(f"✓ {path} ({len(data) / 1024:.1f} KB, {a.pages} 页)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
